const fs=require('node:fs/promises'),path=require('node:path'),assert=require('node:assert/strict');
module.exports=async({context,page,sw,url,root,check})=>{
  await page.evaluate(()=>{GM_setValue('chatKit',{...GM_getValue('chatKit'),wip:false,uiTab:'theme'});return RC.flush();});
  await page.reload();await page.locator('#rc-kit #gear').click();
  await page.emulateMedia({colorScheme:'dark'});
  await page.locator('#rc-kit .body').evaluate(e=>e.scrollTop=60);
  assert.equal(await page.locator('#rc-kit .body').evaluate(e=>getComputedStyle(e,'::-webkit-scrollbar').width),'6px');
  assert.equal(await page.locator('#rc-kit .body').evaluate(e=>getComputedStyle(e,'::-webkit-scrollbar-button').display),'none');
  await page.screenshot({path:path.join(root,'.transfer','v6-dark.png'),animations:'disabled'});
  await page.emulateMedia({colorScheme:'light'});
  await page.screenshot({path:path.join(root,'.transfer','v6-light.png'),animations:'disabled'});
  check('Theme-aware thin scrollbar and range controls');
  const download=page.waitForEvent('download');await page.locator('#theme-export').click();
  const file=await download,doc=JSON.parse(await fs.readFile(await file.path(),'utf8'));
  assert.equal(doc.format,'ultimate-rc-theme');assert.equal(doc.theme.ocrThreads,undefined);
  const before=await page.evaluate(()=>GM_getValue('chatKit'));
  const input=page.locator('#theme-file');
  const upload=async d=>input.setInputFiles({name:'theme.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(d))});
  await upload({...doc,theme:{...doc.theme,primary:'red; color:lime'}});
  await page.waitForFunction(()=>document.body.textContent.includes('Không nhập được'));
  assert.deepEqual(await page.evaluate(()=>GM_getValue('chatKit')),before);
  await Promise.all([page.waitForEvent('domcontentloaded'),upload({...doc,theme:{...doc.theme,primary:'#aabbcc',fontFamily:'Arial',autoTheme:false}})]);
  await page.locator('#gear').waitFor();
  await page.waitForFunction(()=>GM_getValue('chatKit')?.primary==='#aabbcc');
  await page.locator('#gear').waitFor();
  assert.equal(await page.evaluate(()=>GM_getValue('chatKit').ocrThreads),before.ocrThreads);
  check('Theme JSON export/import; invalid input rejected without changing settings');
  const video='data:video/webm;base64,'+(await fs.readFile(path.join(root,'tests/fixtures/wallpaper.webm'))).toString('base64');
  await page.evaluate(async video=>{GM_setValue('chatKitBgVid',video);GM_setValue('chatKit',{...GM_getValue('chatKit'),bgImage:'rc-vid:local',autoTheme:false});await RC.flush();},video);
  await page.reload();await page.locator('#gear').click();
  const vd=page.waitForEvent('download');await page.locator('#theme-export').click();
  const vdoc=JSON.parse(await fs.readFile(await (await vd).path(),'utf8'));assert.equal(vdoc.video,video);
  await page.locator('#clearbg').click();await page.evaluate(()=>RC.flush());
  await Promise.all([page.waitForEvent('domcontentloaded'),upload(vdoc)]);
  await page.locator('#gear').waitFor();
  await page.waitForFunction(()=>GM_getValue('chatKit')?.bgImage==='rc-vid:local');
  assert.equal(await page.evaluate(()=>GM_getValue('chatKitBgVid')),video);
  check('Uploaded video survives portable theme round trip');
  const timings=[];
  const options={url,langs:'eng',threads:1,idle:10,keepWarm:true};
  await page.evaluate(()=>RC.ocrStop());
  for(const threads of [1,2,4]){
    const result=await page.evaluate(o=>RC.ocr(o),{...options,threads});
    assert.match(result.text,/Ultimate RC/i);assert.equal(result.ms.workers,threads);assert.equal(result.ms.backend,'rust');
    timings.push({threads,...result.ms});
  }
  const cached=await page.evaluate(o=>RC.ocr(o),{...options,threads:4,url:url+'?renewed=1'});
  assert.equal(cached.ms.cached,true);timings.push({mode:'content-cache',...cached.ms});
  const warm=await page.evaluate(o=>RC.ocr(o),{...options,threads:4,url:url+'?fresh=1'});
  assert.equal(warm.ms.cached,false);assert.ok(warm.ms.pool<50);assert.match(warm.text,/extension test/i);
  timings.push({mode:'warm-pool',...warm.ms});
  // Cache keys include language/configuration; switching pools cannot overlap active images.
  await page.evaluate(()=>RC.ocrStop());
  const concurrent=await page.evaluate(o=>Promise.all([RC.ocr(o),RC.ocr(o),RC.ocr({...o,langs:'vie+eng',threads:2})]),options);
  assert.equal(concurrent[0].text,concurrent[1].text);
  assert.equal(concurrent[2].ms.workers,2);
  assert.ok(!context.pages().some(p=>p.url().includes('ocr.html')));
  const contexts=await sw.evaluate(()=>chrome.runtime.getContexts({contextTypes:['OFFSCREEN_DOCUMENT']}));assert.equal(contexts.length,1);
  await assert.rejects(page.evaluate(o=>RC.ocr({...o,url:'https://example.com/no.png'}),options),/FPT/);
  await page.evaluate(()=>RC.ocrStop());
  const auto=await page.evaluate(o=>RC.ocr({...o,threads:0,keepWarm:false}),options);
  assert.equal(auto.ms.workers,2);
  await page.waitForFunction(()=>GM_getValue('rc_ocr_status').workers===0);
  await page.evaluate(o=>RC.ocr({...o,idle:0.001}),options);
  await page.waitForFunction(()=>GM_getValue('rc_ocr_status').workers===0);
  await page.evaluate(()=>RC.ocrStop());
  const deferred=await page.evaluate(async o=>{
    const job=RC.ocr({...o,threads:2});
    await new Promise(resolve=>setTimeout(resolve,100));
    const stopped=await RC.ocrStop();await job;return stopped;
  },options);
  assert.equal(deferred.deferred,true);
  await page.waitForFunction(()=>GM_getValue('rc_ocr_status').workers===0);
  check('Idle release and stopping during active OCR finish safely');
  check('Real offscreen OCR: 1/2/4 workers, deduplication, cache, pool switching, auto sizing and release',timings);
  await fs.writeFile(path.join(root,'V6-TEST-RESULTS.json'),JSON.stringify({timings,limitations:'Synthetic English fixture; not a live EduNext latency or accuracy benchmark.'},null,2));
};
