// Settings console: compiled Tailwind/daisyUI CSS, accent/size settings, tabs
// (source/console-ui.js) and resize controls (source/console-size.js).
const TOGGLE_PANEL = `const togglePanel = on => {
            const open = on === undefined ? !panel.classList.contains('open') : on;
            panel.classList.toggle('open', open); $('#gear').setAttribute('aria-expanded', String(open));
            if (open) tabButtons.find(b => b.dataset.tab === currentTab)?.focus({preventScroll:true});
            else $('#gear').focus({preventScroll:true});
        };`;

export async function consoleUI(p, {readText}) {
  p.once("dashboardBg: '#1e293b',", "dashboardBg: '#1e293b', consolePrimary: '#78a6ff', consoleSecondary: '#b6a0ff', consoleWidth: 380, consoleHeight: 620,");
  p.after("['dashboardBg', 'Nền bảng điều khiển'],", "\n            ['consolePrimary', 'Màu chính · bảng điều khiển'],\n            ['consoleSecondary', 'Màu phụ · bảng điều khiển'],");

  // Generated by the Tailwind step of build.mjs; embedded in the shadow root.
  const css = await readText('extension/console.css');
  p.before("        const host = document.createElement('div');\n        host.id = 'rc-kit';", '        const CONSOLE_CSS = ' + JSON.stringify(css) + ';\n');
  p.once('sheet.replaceSync(KIT_CSS);', 'sheet.replaceSync(KIT_CSS + CONSOLE_CSS);');
  p.once('st.textContent = KIT_CSS;', 'st.textContent = KIT_CSS + CONSOLE_CSS;');

  const sizeControls = await readText('source/console-size.js');
  const commandWindow = await readText('source/command-window.js');
  const consoleSource = (await readText('source/console-ui.js'))
    .replace('        /* CONSOLE_SIZE_CONTROLS */', () => sizeControls)
    .replace('        /* RC_COMMAND_WINDOW */', () => commandWindow);
  const tabs = (await readText('source/panel-layout.js')) + '\n' + consoleSource;
  p.between('        const setTab = t => {', "        root.addEventListener('input'", () => tabs + '\n\n');

  // Initial markup stays hidden until the stored selection is applied.
  p.all('class="sec" data-sec=', 'class="sec" hidden data-sec=');
  p.once("const togglePanel = on => { panel.classList.toggle('open', on === undefined ? !panel.classList.contains('open') : on); };", TOGGLE_PANEL);
  p.before("$('#gear')?.addEventListener('click', () => togglePanel());", "$('#gear').setAttribute('aria-expanded', 'false');\n        ");
}
