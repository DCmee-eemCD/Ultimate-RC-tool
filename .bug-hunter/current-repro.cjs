const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const app = fs.readFileSync('extension/app.js', 'utf8');
const enter = app.slice(app.indexOf('    const ENTER_SEL'), app.indexOf('    // =====================================================================', app.indexOf('    const ENTER_SEL')));
const tasks = [];
const sent = [];
const button = {disabled: true, className: 'w-send-btn', getAttribute: () => null, click: () => sent.push(editor.value)};
const scope = {querySelector: () => button};
const editor = {value: 'Original draft', isConnected: true, tagName: 'TEXTAREA', matches: () => true, closest: () => scope};
const ctx = vm.createContext({cfg: {enterSend: true}, window: {addEventListener() {}}, log() {}, Date, setTimeout: fn => tasks.push(fn)});
vm.runInContext(enter, ctx);
ctx.onEnterKey({key: 'Enter', target: editor, preventDefault() {}, stopImmediatePropagation() {}});
editor.value = 'Changed draft that was never submitted';
button.disabled = false;
while (tasks.length) tasks.shift()();
assert.deepEqual(sent, []);
editor.value = 'Unchanged draft';
button.disabled = true;
ctx.onEnterKey({key: 'Enter', target: editor, preventDefault() {}, stopImmediatePropagation() {}});
button.disabled = false;
while (tasks.length) tasks.shift()();
assert.deepEqual(sent, ['Unchanged draft']);
console.log('PASS: delayed Enter rejects changed drafts and sends an unchanged draft once.');

const inputStart = app.indexOf("        root.addEventListener('input', e => {\n            const t = e.target");
const inputEnd = app.indexOf("        $$('[data-theme-mode]')", inputStart);
let inputHandler;
const config = {ocrVie: false, ocrEng: true};
const toggled = {type: 'checkbox', dataset: {k: 'ocrEng'}, checked: false};
vm.runInNewContext(app.slice(inputStart, inputEnd), {root: {addEventListener: (_, fn) => inputHandler = fn}, cfg: config, save() {}, applyTheme() {}, render() {}, toast() {}});
inputHandler({target: toggled});
assert.equal(toggled.checked, true);
assert.equal(config.ocrEng, true);
assert.equal(config.ocrVie, false);
console.log('PASS: sole English checkbox and saved OCR language remain English.');
